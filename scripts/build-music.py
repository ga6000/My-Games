#!/usr/bin/env python3
"""
build-music.py -- turn Suno renders into the embedded loops shared/music.js plays.

WHY EMBEDDED .js AND NOT .mp3 FILES
The file:// hard constraint: a double-clicked page cannot fetch() or XHR a
sibling file, so decodeAudioData would have nothing to decode. A classic
<script src> DOES load under file://, so each track ships as a .js file that
assigns a base64 MP3 into window.PLEURA_TRACKS. Same trick as
scripts/embed-fonts.js.

WHY A HALF-SECOND OF PRE- AND POST-ROLL
MP3 decoders shift audio by an encoder delay that differs between browsers
(~25-50 ms). Each file is [tail of loop][loop][head of loop], and the player
loops between loopStart and loopEnd. Whatever the shift, both loop points move
by the same amount and still land on identical audio, so the loop stays gapless.

Usage (needs ffmpeg, numpy, librosa, soundfile):
  python3 scripts/build-music.py <tracks-dir>
where <tracks-dir> holds the source files named in TRACKS below.
"""
import sys, os, base64, subprocess, tempfile, json
import numpy as np, librosa, soundfile as sf

SR = 44100
ROLL = 0.5
BITRATE = "80k"
# id: (source file, loop start s, loop end s, crossfade s)  -- loop=None = one-shot
TRACKS = {
    "hub":        ("hub-menu_breath-and-bit.mp3", 106.84, 157.36, 0.08),
    "zombie":     ("zombie_same-riff.mp3", 52.15, 81.55, 0.08),
    "rd-arena":   ("rd-arena_walls-breathing.mp3", 34.48, 84.94, 0.08),
    "sting-hook": ("hub-menu_breath-and-bit.mp3", 39.89, 49.99, None),
    "sting-end":  ("end-of-game_sting.wav", 0, None, None),
}

def seamless(y, a, b, xf):
    A, B, X = int(a * SR), int(b * SR), int(xf * SR)
    seg = y[:, A:B + X].copy()
    body = seg[:, :-X].copy()
    w = np.sqrt(np.linspace(0, 1, X))
    body[:, :X] = body[:, :X] * w + seg[:, -X:] * np.sqrt(1 - w ** 2)
    return body

def main(src):
    out_dir = os.path.join(os.path.dirname(__file__), "..", "music")
    for tid, (fn, a, b, xf) in TRACKS.items():
        y, _ = librosa.load(os.path.join(src, fn), sr=SR, mono=True)
        y = y[None, :]
        meta = {}
        if xf is not None:
            L = seamless(y, a, b, xf)
            R = int(ROLL * SR)
            clip = np.concatenate([L[:, -R:], L, L[:, :R]], axis=1)
            meta = {"loopStart": ROLL, "loopEnd": ROLL + L.shape[1] / SR}
        else:
            A = int(a * SR); B = int(b * SR) if b else y.shape[1]
            clip = y[:, A:B].copy()
            n = clip.shape[1]; fi = int(0.01 * SR); fo = int(0.2 * SR)
            clip[:, :fi] *= np.linspace(0, 1, fi); clip[:, n - fo:] *= np.linspace(1, 0, fo)
        clip = clip / max(1.0, np.abs(clip).max() / 0.97)
        with tempfile.TemporaryDirectory() as td:
            w = os.path.join(td, "a.wav"); m = os.path.join(td, "a.mp3")
            sf.write(w, clip.T, SR, subtype="PCM_16")
            subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", w, "-ac", "1",
                            "-b:a", BITRATE, m], check=True)
            b64 = base64.b64encode(open(m, "rb").read()).decode()
        meta["src"] = fn
        js = ("// Generated by scripts/build-music.py -- do not edit by hand.\n"
              "// Source: %s (Suno). See shared/music.js.\n"
              "(window.PLEURA_TRACKS || (window.PLEURA_TRACKS = {}))[%s] =\n"
              "    Object.assign(%s, { mp3: \"%s\" });\n"
              % (fn, json.dumps(tid), json.dumps(meta), b64))
        p = os.path.join(out_dir, tid + ".js")
        open(p, "w").write(js)
        print("%-11s %6.1f s  %4d KB" % (tid, clip.shape[1] / SR, len(js) // 1024))

if __name__ == "__main__":
    main(sys.argv[1])
